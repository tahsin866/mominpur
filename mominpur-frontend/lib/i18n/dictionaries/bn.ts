export type Dictionary = Widen<typeof bn>;

/**
 * `bn` te `as const` ache tai `typeof bn` literal string dey ("বাংলা") —
 * seta English dictionary-r upor apply korle protita value error dey.
 * Widen value ke `string`/`number` kore, kintu key structure strict rakhe.
 * Tai Bangla e notun key add korle English e o add na kora build fail kore —
 * English e extra key add korleo, tai dui language keu chokh khulay rakhte
 * parbe na.
 *
 * Array gulo (`about.facts`, `about.organizers`) o handle korte hobe —
 * otherwise array-r `map`/`length` property gulo porisari Widen hoye jay.
 */
type Widen<T> = T extends string
  ? string
  : T extends number
    ? number
    : T extends boolean
      ? boolean
      : T extends readonly (infer U)[]
        ? readonly Widen<U>[]
        : { [K in keyof T]: Widen<T[K]> };

export default bn;