function norm(s: string): string {
  return s.normalize("NFC").replace(/[\u200C\u200D]/g, "").replace(/\s+/g, " ").trim();
}

function index(rec: Record<string, string>): Map<string, string> {
  const m = new Map<string, string>();
  for (const k in rec) m.set(norm(k), rec[k]);
  return m;
}

const divIdx = index(divisionEn);
const distIdx = index(districtEn);
const thanaIdx = index(thanaEn);

// "হাজীগঞ্জ সদর" -> "হাজীগঞ্জ": Bangla page e "সদর" likha ache, English e chay.
const withoutSadar = (s: string) => s.replace(/\s*সদর$/, "").trim();

const BARE: Record<string, Map<string, string>> = {
  division: new Map([...divIdx].map(([k, v]) => [withoutSadar(k), v])),
  district: new Map([...distIdx].map(([k, v]) => [withoutSadar(k), v])),
  thana: new Map([...thanaIdx].map(([k, v]) => [withoutSadar(k), v])),
};

export function locationEn(
  level: "division" | "district" | "thana",
  bangla: string
): string {
  const map =
    level === "division" ? divIdx : level === "district" ? distIdx : thanaIdx;
  const key = norm(bangla);
  const hit = map.get(key);
  if (hit) return hit;
  const bare = BARE[level].get(withoutSadar(key));
  return bare || bangla;
}
